#!/usr/bin/env node
// Writes android/core/.../AvatarIcons.kt: the preset avatar icons' SVG path data,
// read from `ICONS` in app/src/components.tsx, so the notification draws the
// same icon as the app. `--check` writes nothing and fails when the file on
// disk is not what this would write (CI runs it).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(root, "app/src/components.tsx");
const target = join(root, "android/core/src/main/kotlin/dev/evumi/honk/core/AvatarIcons.kt");

const ts = readFileSync(source, "utf8");
const block = ts.match(/export const ICONS: Record<string, string> = \{([\s\S]*?)\n\};/);
if (!block) {
  console.error(`gen-android-icons: ICONS not found in ${source}`);
  process.exit(1);
}
const icons = [...block[1].matchAll(/^\s*([A-Za-z0-9_]+):\s*"([^"]*)",?\s*$/gm)].map((m) => [m[1], m[2]]);
if (icons.length === 0) {
  console.error("gen-android-icons: ICONS has no entries");
  process.exit(1);
}

const kotlinString = (s) => `"${s.replace(/[\\"$]/g, (c) => `\\${c}`)}"`;
const out = `package dev.evumi.honk.core

// Generated by scripts/gen-android-icons.mjs from ICONS in app/src/components.tsx. Do not edit:
// change the icons there and run \`node scripts/gen-android-icons.mjs\` (CI checks this file is current).

/** The preset avatar icons as SVG path data on a 24-unit grid, drawn stroked (see [SvgPath]). */
object AvatarIcons {
    val PATHS: Map<String, String> = mapOf(
${icons.map(([name, d]) => `        ${kotlinString(name)} to ${kotlinString(d)},`).join("\n")}
    )
}
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {}
  if (current !== out) {
    console.error("gen-android-icons: AvatarIcons.kt is out of date; run `node scripts/gen-android-icons.mjs`");
    process.exit(1);
  }
} else {
  writeFileSync(target, out);
  console.log(`wrote ${icons.length} icons to ${target}`);
}
